def volume_of(scion_id: str) -> dict | None:
    for v in VOLUMES:
        if v["scion"] == scion_id:
            return v
    return None


def section_name(chapter: int, section: int) -> str:
    v = VOLUME_BY_CHAPTER.get(chapter)
    if not v:
        return ""
    if 1 <= section <= len(v["sections"]):
        return v["sections"][section - 1]
    return ""


def catalog() -> list[dict]:
    """目录：按官方展示顺序，附卷名与命途，供界面直接渲染。"""
    out = []
    for ch in CATALOG_ORDER:
        v = VOLUME_BY_CHAPTER[ch]
        s = canon.SCION_BY_ID.get(v["scion"], {})
        out.append({
            "chapter": ch,
            "old": v["old"],
            "new": v["new"],
            "scion": v["scion"],
            "spark": s.get("spark", ""),
            "path": s.get("path", ""),
            "sections": [
                {"idx": i + 1, "zh": name, "roman": _roman(i + 1)}
                for i, name in enumerate(v["sections"])
            ],
            "verse": canon.LIFE_VERSE.get(v["scion"], []),
        })
    return out


_ROMAN = ("I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X")


def _roman(n: int) -> str:
    return _ROMAN[n - 1] if 1 <= n <= len(_ROMAN) else str(n)


def dedication_lines() -> list[str]:
    return DEDICATION["body"].split("\n")
